// Step 1: Create a one-line arrow function that sums two numbers
const sum = (num1, num2) => num1 + num2;

// Step 2: Test the function
console.log(sum(5, 10)); // 15
console.log(sum(0, 0));  // 0
console.log(sum(-3, 7)); // 4

// Explanation:
// - The arrow function receives two parameters: num1 and num2
// - The function returns the sum directly in one line
// - console.log shows the returned value
